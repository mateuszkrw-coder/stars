// Builds js/sky-data.js (naked-eye stars + constellation figures) from the
// d3-celestial package (BSD-3-Clause, (c) 2015 Olaf Frohn):
//   stars: XHIP extended Hipparcos compilation (Anderson & Francis 2012)
//   constellation lines and label positions: IAU, with edits by O. Frohn
//
//   npm pack d3-celestial && tar xzf d3-celestial-*.tgz
//   node tools/make-sky-data.mjs package/data
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const src = process.argv[2];
if (!src) throw new Error('usage: node tools/make-sky-data.mjs <d3-celestial data dir>');
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'js', 'sky-data.js');
const load = (f) => JSON.parse(readFileSync(join(src, f), 'utf8'));
const ra = (lon) => (lon < 0 ? lon + 360 : lon);

// stars: four uint16 per star (RA, Dec, magnitude, B-V), base64
const stars = load('stars.6.json').features
  .map((f) => [ra(f.geometry.coordinates[0]), f.geometry.coordinates[1], +f.properties.mag, parseFloat(f.properties.bv)])
  .filter((s) => s[2] <= 6.0)
  .sort((a, b) => a[2] - b[2]);
const buf = new Uint16Array(stars.length * 4);
stars.forEach((s, i) => {
  const bv = Number.isFinite(s[3]) ? s[3] : 0.6;
  buf[i * 4] = Math.round((s[0] / 360) * 65535);
  buf[i * 4 + 1] = Math.round(((s[1] + 90) / 180) * 65535);
  buf[i * 4 + 2] = Math.round((s[2] + 2) * 1000);
  buf[i * 4 + 3] = Math.max(0, Math.min(65535, Math.round((bv + 0.5) * 10000)));
});
const b64 = Buffer.from(buf.buffer).toString('base64');

// constellation stick figures: [abbr, [[ra, dec, ra, dec, ...], ...]]
const r1 = (x) => Math.round(x * 10) / 10;
const lines = load('constellations.lines.json').features.map((f) => [
  f.id,
  f.geometry.coordinates.map((line) => line.flatMap(([lon, lat]) => [r1(ra(lon)), r1(lat)]))
]);
// names and label positions: [abbr, name, ra, dec]
const names = load('constellations.json').features.map((f) => [
  f.id, f.properties.name, r1(ra(f.geometry.coordinates[0])), r1(f.geometry.coordinates[1])
]);

const js = `/* Cosmic Clocks — the sky seen from Earth. Generated by tools/make-sky-data.mjs; do not edit.
 * Stars: XHIP extended Hipparcos compilation (Anderson & Francis 2012), to magnitude 6.
 * Constellation lines and label positions: IAU, as edited in d3-celestial
 * (BSD-3-Clause, (c) 2015 Olaf Frohn, https://github.com/ofrohn/d3-celestial; licence text in licenses/d3-celestial.txt). */
window.CC = window.CC || {};
CC.SKY = {
  starCount: ${stars.length},
  stars: '${b64}',
  lines: ${JSON.stringify(lines)},
  names: ${JSON.stringify(names)}
};
`;
writeFileSync(out, js);
console.log(`js/sky-data.js: ${stars.length} stars, ${lines.length} figures, ${(js.length / 1024).toFixed(0)} KB`);
